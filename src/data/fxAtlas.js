/** Everything the runtime needs to play effect `id`, or null if unknown. */
export function fxAtlasFor(id) {
  const a = FX_ATLAS[id];
  if (!a) return null;
  return { key: `fx2_${a[0]}`, start: a[1], end: a[1] + a[2] - 1, frames: a[2] };
}
