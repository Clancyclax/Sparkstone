// ===========================================================================
// ROUND 53 -- THE CONFLUENCE GETS A VOICE.
//
// The user, reading a generated Dragon confluence:
//
//   "Hurls a concentrated bolt of Dragon confluence is so uninspired and
//    nonsensical as to be comedic. Confluence essences as concepts should have
//    plenty of information to drive engaging and interesting abilities."
//
// They are right, and the cause was structural rather than a failure of
// vocabulary. `confluenceDefFor` returned { id, name, color, theme, base,
// cooldown } and nothing else -- no family, and crucially no MOTIF. Every other
// slot in the game runs through motifForEssence to get its levers, its body
// parts, its verbs and the clause that says what bonding it does to a body. The
// confluence had none of that, so applyEssenceFlavour bailed on it, no lever
// ever fired, and the description fell through to a stock template sentence.
// Measured across ten random builds: 50 of 50 confluence abilities carried no
// lever at all. The payoff slot was the only slot in the game generating blind.
//
// This file is the missing half. Every one of the 101 authentic confluence
// names gets:
//
//   family  -- what the confluence is MADE of, so materialFor gives it an
//              element and its abilities stop being colourless.
//   parts   -- the concrete nouns it gives a body. These become ability names.
//   verbs   -- what it does, present tense.
//   adjs    -- how it does it.
//   body    -- one clause: what bonding this confluence does to a person.
//
// Those five fields are exactly the motif shape essenceMotifs.js uses, and that
// is the point: the confluence stops being a special case and starts running
// through the same generator as everything else. What it does NOT carry is a
// lever list -- see confluenceMotif in awakening.js. Its levers are the BUILD's
// spine, the thing its own three essences agreed on, which is the user's other
// request answered in the same move: "at least the intersections between the 3
// essences that generate the confluence".
//
// The ~20 marquee confluences additionally carry authored signature abilities;
// those live in confluenceSignatures.js so this file stays one thing.
// ===========================================================================

